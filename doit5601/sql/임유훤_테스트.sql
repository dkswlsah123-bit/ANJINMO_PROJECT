-- ○ 5. 경매 최초 입찰 여부 확인 함수
CREATE OR REPLACE FUNCTION FN_IS_FIRST_BIDDER
(
    P_AUCTION_ID IN NUMBER
)
RETURN CHAR 
IS
    V_COUNT NUMBER;
    V_RESULT CHAR(1);
BEGIN
    -- 입찰 참여 테이블에서 해당 경매의 입찰 기록 개수를 카운트
