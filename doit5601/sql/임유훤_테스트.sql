    ELSIF P_START_PRICE < 10000000 THEN
        -- 100만원 이상 ~ 1,000만원 미만
        V_BID_UNIT := 10000;
        
    ELSE
        -- 1,000만원 이상
        V_BID_UNIT := 100000;
        
    END IF;

    RETURN V_BID_UNIT;
END;
